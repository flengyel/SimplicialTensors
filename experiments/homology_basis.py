"""Exact normalized homology of small tensor-generated modules and graph models."""

import argparse

import numpy as np

from simplicial_tensors.graph_ops import graph_chain_homology
from simplicial_tensors.homology import generated_homology
from simplicial_tensors.rank_shifted import graph_embedding, petersen_edges


def standard_basis_tensor(idx, shape):
    """Return the coordinate tensor E_idx of the supplied shape."""
    tensor = np.zeros(shape, dtype=object)
    tensor[idx] = 1
    return tensor


def compute_homology_dimension(tensor, degree=None, *, modulus=None):
    """Return dim H_degree of the submodule generated by an exact tensor.

    The default degree is min(tensor.shape)-1. Coefficients lie in Q, or
    in F_p when modulus is a prime p. Degrees above the normalized complex
    have dimension zero.
    """
    tensor = np.asarray(tensor)
    result = generated_homology(tensor, modulus=modulus)
    if degree is None:
        degree = min(tensor.shape) - 1
    if not isinstance(degree, (int, np.integer)) or isinstance(degree, (bool, np.bool_)):
        raise TypeError("The homology degree must be an integer.")
    if degree < 0:
        raise ValueError("The homology degree must be nonnegative.")
    return result.homology_dimensions[degree] if degree < len(result.homology_dimensions) else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--modulus", type=int, help="Prime coefficient modulus; default Q")
    args = parser.parse_args()
    examples = {
        "zero": np.zeros((3, 3), dtype=object),
        "vertex": np.array([[1]], dtype=object),
        "circle E01": standard_basis_tensor((0, 1), (2, 2)),
        "3x3 tensor": np.array([[0, 1, 0], [0, 1, 1], [1, 1, 2]], dtype=object),
    }
    print(f"Coefficient field: {'Q' if args.modulus is None else f'F_{args.modulus}'}")
    for label, tensor in examples.items():
        result = generated_homology(tensor, modulus=args.modulus)
        print(f"{label}: normalized dimensions={result.chain_dimensions}, "
              f"boundary ranks={result.boundary_ranks}, Betti numbers={result.homology_dimensions}")
    graphs = {
        "path": graph_embedding(3, [(1, 2), (2, 3)]),
        "cycle": graph_embedding(3, [(1, 2), (2, 3), (3, 1)]),
        "disconnected": graph_embedding(4, [(1, 2), (3, 4)]),
        "Petersen": graph_embedding(10, petersen_edges()),
    }
    for label, graph in graphs.items():
        result = graph_chain_homology(graph, modulus=args.modulus)
        print(f"{label}: normalized dimensions={result.chain_dimensions}, "
              f"boundary ranks={result.boundary_ranks}, Betti numbers={result.homology_dimensions}")


if __name__ == "__main__":
    main()
