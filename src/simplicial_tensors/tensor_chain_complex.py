"""Based normalized tensor complexes with exact sparse ambient lifts."""

from fractions import Fraction
from itertools import combinations
import operator

import numpy as np
import sympy as sp

from .chain_complex import ChainComplex, ExactField
from .rank_shifted import SparseTensor

__all__ = ["generated_chain_complex", "sparse_generated_homology"]


def _fraction(value):
    return Fraction(int(value.p), int(value.q))


def _input_tensor(tensor, field):
    if isinstance(tensor, SparseTensor):
        entries = {index: _fraction(field.scalar(value)) for index, value in tensor.entries.items()}
        return SparseTensor(tensor.degree, tensor.shifts, entries)
    array = np.asarray(tensor)
    if array.ndim == 0 or min(array.shape) == 0:
        raise ValueError("Homology needs nonempty tensor axes.")
    degree = min(array.shape) - 1
    shifts = tuple(length - degree - 1 for length in array.shape)
    entries = {}
    for index in np.ndindex(array.shape):
        value = _fraction(field.scalar(array[index]))
        if value:
            entries[index] = value
    return SparseTensor(degree, shifts, entries)


def _normalized_images(tensor, degree):
    """Use shared sparse faces and Moore projection on injective pullbacks."""
    images = []
    for vertices in combinations(range(tensor.degree + 1), degree + 1):
        image = tensor
        for deleted in reversed(range(tensor.degree + 1)):
            if deleted not in vertices:
                image = image.face(deleted)
        images.append((vertices, image.normalize()))
    return images


def _columns(tensors, labels, field):
    return field.matrix(sp.Matrix(
        len(labels), len(tensors),
        lambda row, column: tensors[column].entries.get(labels[row], Fraction(0)),
    ))


def generated_chain_complex(tensor, *, missing_face=None, modulus=None):
    """Return a based normalized complex for one dense or sparse tensor.

    Sparse input retains its explicit degree and shifts; no dense ambient
    tensor is allocated. Dense input has degree min(shape)-1. Coefficients
    lie in Q, or in F_p for a prime modulus. Rational denominators must be
    invertible in the selected field.

    Supply missing_face to quotient by the submodule generated by the other
    faces. Ambient labels are sparse coordinate tuples. Lift matrices give
    chosen representatives of chain classes, including quotient classes;
    quotient cycle lifts need not be cycles before taking the quotient.
    """
    field = ExactField(modulus)
    tensor = _input_tensor(tensor, field)
    degree, shifts = tensor.degree, tensor.shifts
    if missing_face is not None:
        if isinstance(missing_face, (bool, np.bool_)):
            raise TypeError("The omitted face index must be an integer.")
        try:
            missing_face = operator.index(missing_face)
        except TypeError as exc:
            raise TypeError("The omitted face index must be an integer.") from exc
        if degree == 0 or not 0 <= missing_face <= degree:
            raise ValueError("The omitted face must belong to a positive-degree horn.")
    top = min(degree, len(shifts))
    records = [_normalized_images(tensor, q) for q in range(top + 1)]
    generators = [[image for _, image in values] for values in records]
    relations = []
    for values in records:
        relations.append([] if missing_face is None else [
            image for vertices, image in values
            if any(index != missing_face and index not in vertices for index in range(degree + 1))
        ])

    labels, bases, lifts, relation_dimensions = [], [], [], []
    for q, columns in enumerate(generators):
        positions = {index for column in columns for index in column.entries}
        if q < top:
            positions.update(index for column in generators[q + 1]
                             for index in column.face(0).entries)
        coordinates = tuple(sorted(positions))
        relation_basis = field.column_basis(_columns(relations[q], coordinates, field))
        source_basis = field.column_basis(_columns(columns, coordinates, field))
        combined = field.column_basis(relation_basis.row_join(source_basis))
        if combined.cols != source_basis.cols:
            raise ValueError("Included-face chains are outside the generated submodule.")
        count = relation_basis.cols
        labels.append(coordinates)
        bases.append(combined)
        lifts.append(field.matrix(combined[:, count:]))
        relation_dimensions.append(count)

    dimensions = tuple(lift.cols for lift in lifts)
    differentials = [sp.ImmutableMatrix.zeros(0, dimensions[0])]
    for q in range(1, top + 1):
        images = []
        for column in range(lifts[q].cols):
            representative = SparseTensor(q, shifts, {
                index: _fraction(lifts[q][row, column])
                for row, index in enumerate(labels[q]) if lifts[q][row, column]
            })
            images.append(representative.face(0))
        known = set(labels[q - 1])
        if any(field.scalar(value) != 0 for image in images
               for index, value in image.entries.items() if index not in known):
            raise ValueError("A boundary has coordinates outside the ambient basis.")
        ambient_images = _columns(images, labels[q - 1], field)
        coordinates = field.coordinates(bases[q - 1], ambient_images)
        differentials.append(field.matrix(coordinates[relation_dimensions[q - 1]:, :]))
    return ChainComplex(dimensions, tuple(differentials), modulus=field.modulus,
                        lifts=tuple(lifts), ambient_bases=tuple(labels))


def sparse_generated_homology(tensor, *, missing_face=None, modulus=None):
    """Return field homology dimensions, respecting a SparseTensor's grading."""
    if not isinstance(tensor, SparseTensor):
        raise TypeError("Supply a SparseTensor with explicit degree and shifts.")
    return generated_chain_complex(tensor, missing_face=missing_face, modulus=modulus).homology()
